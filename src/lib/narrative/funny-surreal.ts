// Función para inyectar escenas cómicas/surrealistas en narrativa normal
export function shouldBeeFunnyMoment(): boolean {
  // 10% de eventos deberían ser funny/surreal
  return Math.random() < 0.1;
}

export function pickRandomFunnyMoment(): string {
  const allFunny = [
    ...Object.values(FUNNY_MOMENTS).flat(),
    ...Object.values(FUNNY_TOURNAMENT_MOMENTS).flat(),
  ];
  return allFunny[Math.floor(Math.random() * allFunny.length)];
}

export function getFunnySurreal() {
  return {
    FUNNY_MOMENTS,
    FUNNY_TOURNAMENT_MOMENTS,
    shouldBeeFunnyMoment,
    pickRandomFunnyMoment,
  };
}
